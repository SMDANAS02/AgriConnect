const findBestMatch = (queryText) => {
  const normalised = queryText.toLowerCase().trim();

  let bestMatch = null;
  let bestScore = 0;

  for (const entry of TAMIL_FARMING_KB) {
    let score = 0;
    for (const kw of entry.keywords) {
      const kwLower = kw.toLowerCase();
      if (normalised.includes(kwLower)) {
        // Give bonus points for specific crop or pest keywords
        score += (kwLower.length > 4 ? 2 : 1);
      }
    }
    if (score > bestScore) {
      bestScore = score;
      bestMatch = entry;
    }
  }

  return bestScore > 0 ? bestMatch : null;
};

