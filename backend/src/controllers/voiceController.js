// ─────────────────────────────────────────────────────────────────────────────
// Matching logic — checks all KB entries and returns the best match
// ─────────────────────────────────────────────────────────────────────────────
const findBestMatch = (queryText) => {
  const normalised = queryText.toLowerCase().trim();

  let bestMatch = null;
  let bestScore = 0;

  for (const entry of TAMIL_FARMING_KB) {
    let score = 0;
    for (const kw of entry.keywords) {
      if (normalised.includes(kw.toLowerCase())) {
        score += 1;
      }
    }
    if (score > bestScore) {
      bestScore = score;
      bestMatch = entry;
    }
  }

  return bestScore > 0 ? bestMatch : null;
};

// ─────────────────────────────────────────────────────────────────────────────
// Controller: POST /api/voice/query
// Body: { text: string, context?: string }
// ─────────────────────────────────────────────────────────────────────────────
const queryTamilAssistant = async (req, res, next) => {
  try {
    const { text, context } = req.body;

    if (!text || typeof text !== 'string' || text.trim().length === 0) {
      return errorResponse(res, 400, 'தேடல் உரை வழங்கப்படவில்லை (text field is required)');
    }

    const match = findBestMatch(text);

    if (match) {
      return successResponse(res, 200, 'Tamil farming answer retrieved', {
        answer: match.answer,
        category: match.category,
        matchedQuery: text.trim()
      });
    }

    return successResponse(res, 200, 'General farming advisory', {
      answer: FALLBACK_ANSWER,
      category: 'general',
      matchedQuery: text.trim()
    });
  } catch (error) {
    next(error);
  }
};

